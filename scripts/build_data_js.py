"""Bundle the data files into data/data.js so the page works when opened straight from disk.

Usage:
    python scripts/build_data_js.py

Browsers block a page opened from disk (file://) from fetching its data files, but they do allow
it to load a <script>. data/data.js sets window.RMG_DATA to the text of every file the explorer
uses. Re-run this whenever a file in data/ changes.
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent

FILES = {
    "site_daily": "data/Site_Daily.csv",
    "site_monthly": "data/Site_Monthly.csv",
    "payments": "data/Payments.csv",
    "tariffs": "data/Tariffs.csv",
    "capex": "data/CAPEX.csv",
    "opex": "data/OPEX.csv",
    "meter_links": "data/Meter_Customer_Link.csv",
    "customers": "data/Customers.csv",
    "meter_monthly": "data/meter_monthly.json",
    "fx": "data/fx_rates.csv",
}

data = {k: (root / v).read_text() for k, v in FILES.items()}
body = json.dumps(data, separators=(",", ":")).replace("</", "<\\/")
out = root / "data" / "data.js"
out.write_text(
    "// Generated by scripts/build_data_js.py from the files in data/. Do not edit by hand.\n"
    "window.RMG_DATA = " + body + ";\n"
)
print(f"Wrote {out} ({out.stat().st_size / 1e6:.1f} MB)")
